class Task4:
    val_1 = 0
    val_2 = 0

    def __init__(self,x):
        if type(x) == float and int(x) <= 256:
            self.val_1 = chr(int(x // 1))
            self.val_2 = int(x % 1 * 100)
            print(self.val_1, self.val_2)
        else:
            print('Введите вещественное число, которое меньше 127')

