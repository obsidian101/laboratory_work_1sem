# В классе должен быть конструктор с двумя параметрами:
# целое число и символ задают оба поля.
# Добавьте конструктор с одним вещественным аргументом.
# Целая часть числа станет кодом символа.
# Дробная часть (десятые и сотые) задаст целое.
# Например, 65.1267 даст символ 'A' и число 12.
